enum class AppTab(val title: String) {
    HOME("Home"),
    RECITERS("Reciters"),
    PLAYLISTS("Playlists"),
    SETTINGS("Settings")
}

@Composable
fun BottomNavBar(
    selectedTab: AppTab,
    onTabSelected: (AppTab) -> Unit,
    modifier: Modifier = Modifier
) {
    Box(
        modifier = modifier
            .fillMaxWidth()
            .background(Color(0xE60A0A0A))
            .navigationBarsPadding()
            .padding(horizontal = 16.dp, vertical = 6.dp)
    ) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.SpaceAround,
            verticalAlignment = Alignment.CenterVertically
        ) {
            val tabs = listOf(
                Triple(AppTab.HOME, "Home", Icons.Default.Home),
                Triple(AppTab.RECITERS, "Reciters", Icons.Default.Person),
                Triple(AppTab.PLAYLISTS, "Playlists", Icons.AutoMirrored.Filled.QueueMusic),
                Triple(AppTab.SETTINGS, "Settings", Icons.Default.Settings)
            )

            tabs.forEach { (tab, label, icon) ->
                val isSelected = selectedTab == tab
                val tint = if (isSelected) Color.White else Color.White.copy(alpha = 0.5f)

                Column(
                    modifier = Modifier
                        .testTag("tab_${tab.name.lowercase()}")
                        .clip(RoundedCornerShape(12.dp))
                        .clickable(
                            interactionSource = remember { MutableInteractionSource() },
                            indication = null
                        ) { onTabSelected(tab) }
                        .padding(horizontal = 12.dp, vertical = 4.dp),
                    horizontalAlignment = Alignment.CenterHorizontally
                ) {
                    Icon(
                        imageVector = icon,
                        contentDescription = label,
                        tint = tint,
                        modifier = Modifier.size(24.dp)
                    )
                    Text(
                        text = label,
                        color = tint,
                        fontSize = 11.sp,
                        fontWeight = if (isSelected) FontWeight.SemiBold else FontWeight.Normal
                    )
                }
            }
        }
    }
}
